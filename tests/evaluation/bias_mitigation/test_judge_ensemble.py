"""Tests for judge ensemble and self-enhancement bias mitigation."""

import pytest
from src.evaluation.bias_mitigation.judge_ensemble import (
    ConfigurationError,
    EnsembleVerdict,
    MinorityVetoEnsemble,
)


def make_mock_judge(score: float, model: str = "mock-model"):
    def judge(response_text: str, **kwargs):
        return {"score": score, "model": model}
    return judge


def test_configuration_error_on_fewer_than_two_providers():
    # Only 1 judge -> error
    with pytest.raises(ConfigurationError, match="at least 2"):
        MinorityVetoEnsemble([
            ("openai", make_mock_judge(4.0))
        ])

    # 2 judges from same provider -> error
    with pytest.raises(ConfigurationError, match="at least 2 distinct model families/providers"):
        MinorityVetoEnsemble([
            ("openai", make_mock_judge(4.0)),
            ("openai", make_mock_judge(3.5)),
        ])


def test_valid_init_with_two_or_more_providers():
    ensemble = MinorityVetoEnsemble([
        ("openai", make_mock_judge(4.0)),
        ("anthropic", make_mock_judge(4.5)),
    ])
    assert len(ensemble.distinct_providers) == 2
    assert "openai" in ensemble.distinct_providers
    assert "anthropic" in ensemble.distinct_providers


def test_self_family_recusal():
    """Verify that when evaluating an OpenAI response, the OpenAI judge is recused."""
    ensemble = MinorityVetoEnsemble([
        ("openai", make_mock_judge(5.0)),
        ("anthropic", make_mock_judge(3.0)),
        ("google", make_mock_judge(4.0)),
    ])

    verdict = ensemble.evaluate(
        response_text="test response",
        response_provider="openai",
    )

    assert isinstance(verdict, EnsembleVerdict)
    assert verdict.recused_provider == "openai"
    assert verdict.recusal_unverified is False
    assert "openai" not in verdict.scores_by_provider
    assert "anthropic" in verdict.scores_by_provider
    assert "google" in verdict.scores_by_provider
    # Scores voted: 3.0 and 4.0 -> median is (3.0 + 4.0) / 2 = 3.5
    assert verdict.final_score == 3.5
    assert verdict.high_disagreement is False


def test_no_recusal_when_provider_not_in_ensemble():
    """If response was generated by 'mistral', all judges vote because none are mistral."""
    ensemble = MinorityVetoEnsemble([
        ("openai", make_mock_judge(4.0)),
        ("anthropic", make_mock_judge(4.2)),
    ])

    verdict = ensemble.evaluate(
        response_text="r",
        response_provider="mistral",
    )

    assert verdict.recused_provider is None
    assert verdict.recusal_unverified is False
    assert len(verdict.scores_by_provider) == 2
    assert verdict.final_score == pytest.approx(4.1)


def test_missing_provider_flags_recusal_unverified():
    """If response_provider is None or empty string, do not crash; flag recusal_unverified."""
    ensemble = MinorityVetoEnsemble([
        ("openai", make_mock_judge(4.0)),
        ("anthropic", make_mock_judge(4.0)),
    ])

    verdict = ensemble.evaluate(
        response_text="r",
        response_provider=None,
    )

    assert verdict.recusal_unverified is True
    assert verdict.recused_provider is None
    assert len(verdict.scores_by_provider) == 2
    assert verdict.final_score == 4.0


def test_high_disagreement_detection():
    """When max(score) - min(score) > disagreement_threshold, flag high_disagreement=True."""
    ensemble = MinorityVetoEnsemble(
        judges=[
            ("openai", make_mock_judge(1.0)),
            ("anthropic", make_mock_judge(4.5)),
            ("cohere", make_mock_judge(2.0)),
        ],
        disagreement_threshold=2.0,
    )

    # spread is 4.5 - 1.0 = 3.5 > 2.0
    verdict = ensemble.evaluate(
        response_text="r",
        response_provider="meta",
    )

    assert verdict.high_disagreement is True
    spread = max(verdict.scores_by_provider.values()) - min(verdict.scores_by_provider.values())
    assert spread == 3.5
    # Scores: 1.0, 2.0, 4.5 -> median is 2.0
    assert verdict.final_score == 2.0


def test_low_disagreement():
    ensemble = MinorityVetoEnsemble(
        judges=[
            ("openai", make_mock_judge(4.0)),
            ("anthropic", make_mock_judge(4.5)),
            ("google", make_mock_judge(4.2)),
        ],
        disagreement_threshold=2.0,
    )

    # spread is 4.5 - 4.0 = 0.5 <= 2.0
    verdict = ensemble.evaluate(
        response_text="r",
        response_provider="meta",
    )

    assert verdict.high_disagreement is False
    spread = max(verdict.scores_by_provider.values()) - min(verdict.scores_by_provider.values())
    assert spread == pytest.approx(0.5)
    assert verdict.final_score == 4.2


def test_recusal_leaving_no_judges_raises_runtime_error():
    """If all judges happen to be from the recused provider, raises RuntimeError."""
    # Force bypass init validation to test evaluate guard
    ensemble = MinorityVetoEnsemble.__new__(MinorityVetoEnsemble)
    ensemble.judges = [("openai", make_mock_judge(4.0))]
    ensemble.disagreement_threshold = 2.0

    with pytest.raises(RuntimeError, match="All judges in the ensemble were recused"):
        ensemble.evaluate("test text", response_provider="openai")

