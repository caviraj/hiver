"""Pydantic schemas for RAGAS evaluation components."""

from typing import List, Optional
from pydantic import BaseModel, Field


class RAGASInput(BaseModel):
    """Input payload for RAGAS evaluation.

    Attributes:
        query: The user query or question.
        retrieved_contexts: Chunks retrieved by the retrieval pipeline.
        generated_response: Text generated by LLM (or test response).
        reference_answer: Optional ground truth reference answer. When None,
            precision and recall cannot be computed and remain None.
    """

    query: str
    retrieved_contexts: List[str]
    generated_response: str
    reference_answer: Optional[str] = None


class RAGASResult(BaseModel):
    """Output results of RAGAS evaluation.

    Semantic note on Optional[float]:
        None indicates 'undefined / not computed' (e.g., no reference answer
        provided for context precision/recall, or empty contexts/claims).
        0.0 indicates 'computed and scored poorly'.
        These must never be conflated.
    """

    context_precision: Optional[float] = None
    context_recall: Optional[float] = None
    faithfulness: Optional[float] = None
    num_claims_extracted: int = 0
    num_claims_supported: int = 0
    notes: List[str] = Field(default_factory=list)


class GEvalResult(BaseModel):
    """Output results of G-Eval logit-weighted holistic scoring.

    Attributes:
        rubric_name: Dimension evaluated ('brand_tone', 'empathy', 'structural_coherence').
        weighted_score: Continuous score computed via logit-weighted expectation.
        captured_probability_mass: Total unnormalized probability mass captured across
            valid score tokens ('1' through '5'). Used to detect low-confidence extractions.
        cot_reasoning_text: Chain-of-Thought reasoning generated by the model prior to scoring.
        low_confidence: True if captured_probability_mass < 0.5, indicating weak statistical anchor.
        logprobs_unavailable: True if provider/model does not expose logprobs and fell back
            to integer extraction from text.
        notes: Informational or diagnostic notes (e.g. degenerate input warnings).
    """

    rubric_name: str
    weighted_score: float
    captured_probability_mass: float
    cot_reasoning_text: str
    low_confidence: bool = False
    logprobs_unavailable: bool = False
    notes: List[str] = Field(default_factory=list)

