"""Claim extraction and verification for Faithfulness evaluation using HHEM-2.1-Open or NLI models."""

import logging
import re
from typing import Any, List, Optional, Tuple

logger = logging.getLogger(__name__)


def extract_claims(generated_response: str, hhem_model: Any = None) -> List[str]:
    """Extract verifiable atomic factual claims from a generated response.

    If the model provides a custom claim extractor, it is invoked;
    otherwise, sentences are extracted and filtered for substantive factual claims.

    Args:
        generated_response: Response text generated by the model.
        hhem_model: Optional HHEM model or claim extractor instance.

    Returns:
        List[str]: Extracted claim statements.
    """
    if not generated_response or not generated_response.strip():
        return []

    # If the model has an extract_claims method, delegate to it
    if hasattr(hhem_model, "extract_claims") and callable(hhem_model.extract_claims):
        try:
            custom_claims = hhem_model.extract_claims(generated_response)
            if isinstance(custom_claims, list):
                return [str(c).strip() for c in custom_claims if str(c).strip()]
        except Exception as e:
            logger.warning("Custom extract_claims failed: %s. Falling back to default extraction.", e)

    # Standard sentence-based claim segmentation
    raw_sentences = re.split(r"(?<=[.!?])\s+|\n+", generated_response.strip())
    claims = []
    # Common conversational non-claims to filter out
    trivial_patterns = {
        r"^(hello|hi|hey|greetings|thank you|thanks|sure|okay|here is|here are)\b",
        r"^(hope this helps|let me know|regards|best)\b",
    }

    for s in raw_sentences:
        s_clean = s.strip().strip("-*123456789.) ")
        if len(s_clean) < 8:  # Skip trivial fragments
            continue
        # Skip purely conversational greetings/closings
        is_trivial = any(re.search(pat, s_clean, re.IGNORECASE) for pat in trivial_patterns)
        if not is_trivial:
            claims.append(s_clean)

    return claims


def _predict_consistency(hhem_model: Any, premise: str, hypothesis: str) -> float:
    """Predict factual consistency score in [0.0, 1.0] between premise and hypothesis."""
    try:
        # Case 1: Model has a predict method (like CrossEncoder, SentenceTransformers, or Vectara HHEM)
        if hasattr(hhem_model, "predict") and callable(hhem_model.predict):
            res = hhem_model.predict([(premise, hypothesis)])
            # Handle float, list, or numpy array
            if hasattr(res, "__getitem__"):
                return float(res[0])
            return float(res)

        # Case 2: Model is directly callable
        if callable(hhem_model):
            try:
                res = hhem_model(premise, hypothesis)
                if isinstance(res, (float, int)):
                    return float(res)
            except TypeError:
                pass
            res = hhem_model([(premise, hypothesis)])
            if hasattr(res, "__getitem__"):
                return float(res[0])
            return float(res)

        # Case 3: HuggingFace pipeline
        if hasattr(hhem_model, "__call__"):
            res = hhem_model(f"{premise}</s></s>{hypothesis}")
            if isinstance(res, list) and len(res) > 0 and isinstance(res[0], dict):
                return float(res[0].get("score", 0.0))

        raise ValueError(f"Unsupported model invocation interface for: {type(hhem_model)}")
    except Exception as e:
        logger.warning("Error predicting consistency between premise and claim: %s", e)
        return 0.0


def verify_claims(
    claims: List[str],
    retrieved_contexts: List[str],
    hhem_model: Any,
    threshold: float = 0.5,
) -> List[bool]:
    """Verify each claim against retrieved contexts using HHEM-2.1-Open or equivalent.

    A claim is considered supported (True) if its consistency score against
    ANY retrieved context (or combined contexts) meets or exceeds `threshold`.

    Args:
        claims: List of factual claims to verify.
        retrieved_contexts: Retrieved context chunks.
        hhem_model: Loaded HHEM model or callable judge.
        threshold: Minimum probability threshold for support (default 0.5).

    Returns:
        List[bool]: Support indicators for each claim in order.
    """
    if not claims or not retrieved_contexts or hhem_model is None:
        return [False] * len(claims)

    results: List[bool] = []

    for claim in claims:
        claim_supported = False
        # Check against each context chunk individually
        for ctx in retrieved_contexts:
            ctx_str = ctx.strip()
            if not ctx_str:
                continue
            score = _predict_consistency(hhem_model, premise=ctx_str, hypothesis=claim)
            if score >= threshold:
                claim_supported = True
                break

        # If not verified against individual chunks, test against concatenated context
        if not claim_supported and len(retrieved_contexts) > 1:
            combined_ctx = " ".join(c.strip() for c in retrieved_contexts if c.strip())
            score = _predict_consistency(hhem_model, premise=combined_ctx, hypothesis=claim)
            if score >= threshold:
                claim_supported = True

        results.append(claim_supported)

    return results


def compute_faithfulness(
    generated_response: str,
    retrieved_contexts: List[str],
    hhem_model: Any,
    threshold: float = 0.5,
) -> Tuple[Optional[float], int, int]:
    """Compute Faithfulness score of generated response against retrieved contexts.

    Formula:
        Faithfulness = num_claims_supported / num_claims_extracted

    Semantics:
        - If 0 claims extracted: returns (None, 0, 0) because faithfulness is UNDEFINED
          for responses without factual claims, not 0.0.
        - If retrieved_contexts is empty: returns (None, num_claims, 0) because claims
          cannot be verified against an empty context.
        - If num_claims > 0 and 0 are supported: returns (0.0, num_claims, 0), which
          represents a valid strong hallucination signal.

    Args:
        generated_response: Response generated by the LLM.
        retrieved_contexts: Retrieved context chunks.
        hhem_model: HHEM-2.1-Open model or mock.
        threshold: Decision threshold for claim support (default 0.5).

    Returns:
        Tuple[Optional[float], int, int]: (faithfulness_score, num_claims, num_supported).
    """
    claims = extract_claims(generated_response, hhem_model)
    num_claims = len(claims)

    if num_claims == 0:
        return (None, 0, 0)

    if not retrieved_contexts:
        return (None, num_claims, 0)

    verifications = verify_claims(claims, retrieved_contexts, hhem_model, threshold=threshold)
    num_supported = sum(1 for is_supp in verifications if is_supp)

    faithfulness_score = num_supported / num_claims
    return (float(faithfulness_score), num_claims, num_supported)
